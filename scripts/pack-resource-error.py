#!/usr/bin/env python3
"""Build the self-contained missing-resource screen and its RGB565 RLE data."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]

def pack(source,index):
    image=Image.new('RGB',(240,240),'#edf6fc')
    draw=ImageDraw.Draw(image)
    ink='#394c71'; muted='#61758f'
    def text(label,size,y,color=ink):
        font=ImageFont.truetype(str(source),size,index=index)
        box=draw.textbbox((0,0),label,font=font)
        draw.text(((240-box[2]+box[0])//2-box[0],y-box[1]),label,font=font,fill=color)
    text('CODEX',14,12)
    # Simple TF card pictogram: no external art or font is needed at runtime.
    draw.rounded_rectangle((77,48,163,140),radius=13,fill='#d4e6f4',outline=ink,width=3)
    draw.polygon([(78,49),(99,49),(78,70)],fill='#edf6fc')
    draw.line([(78,70),(99,49)],fill=ink,width=3)
    for x in range(101,151,13): draw.rounded_rectangle((x,57,x+6,74),radius=2,fill='#90aec7')
    draw.ellipse((102,87,138,123),fill='#f4bd58')
    draw.rounded_rectangle((118,94,122,108),radius=2,fill=ink)
    draw.ellipse((118,113,122,117),fill=ink)
    text('资源缺失',20,158)
    text('请检查 TF 卡',14,191,muted)
    text('补齐资源后重启',14,215,muted)
    image.save(ROOT/'firmware/assets/resource-missing.png')
    values=[]
    for red,green,blue in image.get_flattened_data():
        values.append(((red>>3)<<11)|((green>>2)<<5)|(blue>>3))
    runs=[]
    for color in values:
        if runs and runs[-1][1]==color and runs[-1][0]<65535: runs[-1][0]+=1
        else: runs.append([1,color])
    header='/* Generated by scripts/pack-resource-error.py; Noto Sans CJK SC, SIL OFL 1.1. */\n'
    header+='#ifndef PET_RESOURCE_MISSING_DATA_H\n#define PET_RESOURCE_MISSING_DATA_H\n#include <stdint.h>\n'
    header+='static const uint16_t pet_resource_missing_runs[][2]={\n'
    header+=''.join(f' {{{count},0x{color:04x}}},\n' for count,color in runs)
    header+='};\n#endif\n'
    (ROOT/'firmware/assets/resource_missing.h').write_text(header)
    print(f'Fallback image: {len(runs)*4} bytes RGB565 RLE')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('font',type=Path)
    parser.add_argument('--index',type=int,default=0)
    args=parser.parse_args();pack(args.font,args.index)
